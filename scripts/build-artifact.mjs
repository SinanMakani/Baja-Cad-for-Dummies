// Build the claude.ai Artifact version of the app into dist-artifact/.
//
//   npm run build:artifact
//
// Runs the same Vite build as `npm run build` (same config, same bundle) but
// writes it to dist-artifact/, leaving dist/ alone. Then it rewrites
// index.html into the page the Artifact publisher expects:
//   - no <!doctype>, <html>, <head> or <body>: the publisher wraps the page in
//     its own skeleton (charset and viewport meta plus a small CSS reset), so
//     those tags and the charset, viewport and description metas are dropped;
//   - <title> comes first (the artifact's name is read from the first 8 KB);
//   - asset URLs stay relative (vite.config.js uses base './'), and every file
//     under assets/ is published next to the page, the OpenCascade .wasm
//     included. The artifact's CSP blocks other hosts apart from a few script
//     CDNs and Google Fonts, which the page keeps;
//   - crossorigin attributes are dropped from the page's own assets.
// Finally it writes dist-artifact/artifact-files.json (the `files` map to
// publish, with media types) and checks every file against the size limits.
//
// The app detects the artifact at run time (src/platform/artifact.js), so the
// JavaScript bundle is exactly the one `npm run build` makes.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'dist-artifact');
const rel = (f) => path.relative(root, f).split(path.sep).join('/');

await build({ root, logLevel: 'warn', build: { outDir, emptyOutDir: true } });

// ------------------------------------------------------------------ page
const htmlFile = path.join(outDir, 'index.html');
const html = fs.readFileSync(htmlFile, 'utf8');
const inner = (tag) => {
  const m = new RegExp(`<${tag}[^>]*>([\\s\\S]*)</${tag}>`, 'i').exec(html);
  if (!m) throw new Error(`${rel(htmlFile)} has no <${tag}>`);
  return m[1];
};
const TAG = /<(title|script|style|noscript)\b[^>]*>[\s\S]*?<\/\1>|<(?:meta|link)\b[^>]*>/gi;
const headTags = inner('head').match(TAG) || [];
const own = (tag) => tag.replace(/\s+crossorigin(=("[^"]*"|'[^']*'|[^\s>]+))?(?=[\s>])/i, '');

const title = headTags.find((t) => /^<title/i.test(t));
if (!title) throw new Error('index.html has no <title>');
const keep = headTags.filter((t) => t !== title && !/^<meta\b/i.test(t));
const isAsset = (t) => /\b(?:src|href)="\.\/assets\//.test(t);
const scripts = keep.filter((t) => /^<script/i.test(t));
const links = keep.filter((t) => !/^<script/i.test(t)).map((t) => (isAsset(t) ? own(t) : t));

const page = [
  title,
  '<!-- claude.ai Artifact build of Baja Vehicle Designer. Generated by scripts/build-artifact.mjs from index.html; edit the source, not this file. -->',
  ...links,
  ...inner('body').split('\n').map((l) => l.trim()).filter(Boolean),
  ...scripts.map((t) => (isAsset(t) ? own(t) : t)),
  '',
].join('\n');
fs.writeFileSync(htmlFile, page);

// Every reference must be one of the published files or Google Fonts.
for (const [, url] of page.matchAll(/\b(?:src|href)="([^"]+)"/g)) {
  if (/^https:\/\/fonts\.(googleapis|gstatic)\.com(\/|$)/.test(url)) continue;
  if (/^[a-z]+:|^\/\//i.test(url)) throw new Error(`index.html loads ${url}; the artifact's CSP would block it`);
  if (!fs.existsSync(path.join(outDir, url))) throw new Error(`index.html references ${url}, which the build did not write`);
}

// ------------------------------------------------------------------ files
const TYPES = { '.js': 'text/javascript', '.css': 'text/css', '.wasm': 'application/wasm', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.woff2': 'font/woff2' };
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
const MB = 1024 * 1024;
const files = {};
let total = fs.statSync(htmlFile).size;
const rows = [['index.html', total]];
for (const f of walk(path.join(outDir, 'assets')).sort()) {
  const ext = path.extname(f).toLowerCase();
  const type = TYPES[ext];
  if (!type) throw new Error(`No media type for ${rel(f)}; add ${ext} to TYPES in scripts/build-artifact.mjs`);
  const size = fs.statSync(f).size;
  const limit = /^(text|application\/json|image\/svg)/.test(type) ? 16 * MB : 15 * MB;
  if (size > limit) throw new Error(`${rel(f)} is ${(size / MB).toFixed(1)} MB; artifact files are limited to ${limit / MB} MB`);
  const published = path.relative(outDir, f).split(path.sep).join('/');
  files[published] = { from: rel(f), contentType: type };
  rows.push([published, size]);
  total += size;
}
if (total > 64 * MB) throw new Error(`The build is ${(total / MB).toFixed(1)} MB; one publish sends at most 64 MB`);
fs.writeFileSync(path.join(outDir, 'artifact-files.json'), `${JSON.stringify({ page: rel(htmlFile), files }, null, 2)}\n`);

const kb = (n) => `${(n / 1024).toFixed(1).padStart(8)} KB`;
console.log(`\nArtifact build in ${rel(outDir)}/ (publish the page with every file below):`);
for (const [name, size] of rows) console.log(`  ${kb(size)}  ${name}`);
console.log(`  ${kb(total)}  total\nFiles map for publishing: ${rel(outDir)}/artifact-files.json`);
